export function inferVehicleCategory(v: Vehicle): VehicleCategory {
  if (v.category) return v.category;
  const text = `${v.brand} ${v.model} ${v.version}`.toLowerCase();
  if (
    text.includes('911') ||
    text.includes('carrera') ||
    text.includes('cayman') ||
    text.includes('coupe') ||
    text.includes('mustang')
  ) {
    return 'Esportivos';
  }
  if (
    text.includes('golf') ||
    text.includes('polo') ||
    text.includes('a3 sportback') ||
    text.includes('hatch') ||
    text.includes('mini')
  ) {
    return 'Hatches';
  }
  if (
    text.includes('macan') ||
    text.includes('compass') ||
    text.includes('corolla cross') ||
    text.includes('suv') ||
    text.includes('nivus') ||
    text.includes('t-cross') ||
    text.includes('tiguan')
  ) {
    return 'SUVs';
  }
  return 'Sedans';
}

